/**
 * The formula bank: well-known equations by discipline, each symbol tied to the
 * concept it stands for there. A starting point, not knowledge the app depends
 * on: picking an entry in New Formula builds it fully formed (buildFormula.js),
 * and from then on it is ordinary Things to edit. Nothing ever recognizes typed
 * text as one of these.
 *
 * The same letter means different things in different places (P is pressure,
 * power, principal, price, probability), so the meaning lives on each equation:
 * `symbols` maps every symbol in its text to a concept. Each concept becomes one
 * Thing, named for what it is (Pressure) and written by its symbol in formulas
 * (its formula label, P), so the same concept is one Thing across every
 * equation that uses it. A concept is written the same way everywhere it
 * appears (test/canvas/formulaBank.test.js holds the bank to that).
 *
 * Text is read as standard math (parseFormulaText, convention 'math') with the
 * equation's symbols as known names, so KE and ΔU read whole. `a_b` is a symbol
 * with a subscript. An entry the notation can't write yet carries `unsupported`
 * (what it lacks) and is listed but not offered.
 */

