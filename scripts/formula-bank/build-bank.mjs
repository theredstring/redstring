#!/usr/bin/env node
/**
 * Build the formula bank from the snapshot fetch-wikidata.mjs wrote. The
 * building itself is shared with the app (Settings → Data → Formula Bank):
 * src/components/canvas/formats/formula/bank/population/buildBank.js, which
 * says what gets in.
 *
 *   node scripts/formula-bank/build-bank.mjs
 *
 * Writes the bank the app ships with (bank.generated.json), its report
 * (bank.report.json, shown in Settings → Data), and REPORT.md beside this
 * script, to read.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildBank } from '../../src/components/canvas/formats/formula/bank/population/buildBank.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const BANK_DIR = resolve(HERE, '../../src/components/canvas/formats/formula/bank');

const snapshot = JSON.parse(readFileSync(resolve(HERE, 'wikidata-snapshot.json'), 'utf8'));
const { bank, report } = buildBank(snapshot);
writeFileSync(resolve(BANK_DIR, 'bank.generated.json'), `${JSON.stringify(bank, null, 1)}\n`);
writeFileSync(resolve(BANK_DIR, 'bank.report.json'), `${JSON.stringify(report)}\n`);

const lines = [
  '# Formula bank build report',
  '',
  `From ${report.source}, fetched ${report.fetchedAt}. Generated by build-bank.mjs; do not edit by hand.`,
  '',
  `**${report.accepted} of ${report.total} items** are in the bank, ${report.concepts} concepts between them.`,
  '',
  '## By discipline',
  '',
  ...report.byDiscipline.map(([d, n]) => `- ${d}: ${n}`),
  '',
  '## Left out',
  '',
  ...report.byReason.map(([r, n]) => `- ${r}: ${n}`),
  '',
  '### What the notation can\'t write yet',
  '',
  ...report.whyNot.slice(0, 25).map(([r, n]) => `- ${r}: ${n}`),
  '',
  'Every item left out, with its reason, is in bank.report.json (and in Settings → Data → Formula Bank).',
  '',
];
writeFileSync(resolve(HERE, 'REPORT.md'), lines.join('\n'));
console.log(lines.slice(4, 22).join('\n'));
