#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES: the name, version, licence and licence text
// of every runtime (non-dev) npm dependency, read offline from node_modules.
// Distributing the app (web, desktop, mobile) requires these notices, and the
// LGPL-3.0 components (heic-to, which bundles libheif/libde265 compiled to
// WebAssembly) additionally need a written source offer, included below.
//
//   node scripts/security/third-party-notices.mjs                        # print to stdout
//   node scripts/security/third-party-notices.mjs --out dist/THIRD_PARTY_NOTICES.txt
//   node scripts/security/third-party-notices.mjs --capacitor            # store builds: heic-to is aliased away
//   node scripts/security/third-party-notices.mjs --check                # exit 1 if any package has no licence
//
// Run it after `npm run build` with --out dist/... so the file ships inside
// every build (Pages serves it, electron-builder packs dist/, cap sync copies it).

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

// Packages whose licence needs more than attribution, with the source offer
// text to include. Keep in step with documentation/security/THREAT_MODEL.md.
const COPYLEFT = {
  'heic-to': {
    components: 'heic-to (JavaScript wrapper) and the libheif and libde265 libraries it bundles, compiled to WebAssembly',
    source: [
      'https://github.com/hoppergee/heic-to (the exact version is listed below)',
      'https://github.com/strukturag/libheif',
      'https://github.com/strukturag/libde265',
    ],
  },
};

function productionPackages({ capacitor }) {
  let out = '';
  try {
    out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch (e) {
    out = e.stdout || ''; // npm ls exits non-zero on peer-dep warnings but still prints the tree
  }
  const tree = JSON.parse(out || '{}');
  const seen = new Map();
  // Walk from package.json's runtime dependencies. Extraneous packages (in
  // node_modules but not in this project's tree) are not shipped, so skip them.
  const visit = (deps) => {
    for (const [name, node] of Object.entries(deps || {})) {
      if (!node || node.extraneous || node.missing || !node.path) continue;
      if (capacitor && name === 'heic-to') continue; // replaced by src/utils/heicUnsupportedStub.js in store builds
      const key = `${name}@${node.version}`;
      if (seen.has(key)) continue;
      let pkg = {};
      try { pkg = JSON.parse(fs.readFileSync(path.join(node.path, 'package.json'), 'utf8')); } catch { /* use npm's data */ }
      const license = (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type)
        ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type ?? l).join(' OR ') : null)
        ?? (typeof node.license === 'string' ? node.license : null);
      let text = null;
      try {
        const f = fs.readdirSync(node.path).find((n) => LICENSE_FILE.test(n));
        if (f) text = fs.readFileSync(path.join(node.path, f), 'utf8').trim();
      } catch { /* unreadable dir */ }
      const source = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
      seen.set(key, { name, version: node.version, license: license || 'UNKNOWN', text, url: pkg.homepage || source || null });
      visit(node.dependencies);
    }
  };
  visit(tree.dependencies);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function renderNotices(pkgs) {
  const lines = [
    'THIRD-PARTY SOFTWARE NOTICES — Redstring',
    '',
    'Redstring includes the open-source packages listed below. Each is distributed under its own licence;',
    'the licence texts follow the list. Generated by scripts/security/third-party-notices.mjs.',
    '',
  ];
  const copyleft = pkgs.filter((p) => COPYLEFT[p.name]);
  if (copyleft.length) {
    lines.push('LGPL COMPONENTS AND SOURCE OFFER', '');
    for (const p of copyleft) {
      const c = COPYLEFT[p.name];
      lines.push(
        `${p.name}@${p.version} (${p.license}): ${c.components}.`,
        'These components are licensed under the GNU Lesser General Public License v3.0. You may obtain the',
        'complete corresponding source code from:',
        ...c.source.map((s) => `  ${s}`),
        'or, for three years from the date you received this software, by writing to info@redstring.io and we',
        'will provide a copy of the corresponding source for no more than the cost of distribution. You may',
        'modify these components and replace them in the web and desktop builds (they are loaded as separate',
        'JavaScript/WebAssembly modules).',
        '',
      );
    }
  }
  lines.push('PACKAGES', '');
  for (const p of pkgs) lines.push(`${p.name}@${p.version}  ${p.license}${p.url ? `  ${p.url.replace(/^git\+/, '')}` : ''}`);
  lines.push('', 'LICENCE TEXTS', '');
  // One text per package: most MIT copies differ by their copyright line.
  for (const p of pkgs) {
    lines.push('-'.repeat(78), `${p.name}@${p.version} (${p.license})`, '');
    lines.push(p.text || `No licence file shipped with the package; declared licence: ${p.license}.`, '');
  }
  return `${lines.join('\n')}\n`;
}

function main(argv = process.argv.slice(2)) {
  const pkgs = productionPackages({ capacitor: argv.includes('--capacitor') });
  if (argv.includes('--check')) {
    const unknown = pkgs.filter((p) => p.license === 'UNKNOWN');
    if (unknown.length) {
      console.error(`third-party-notices: ${unknown.length} package(s) declare no licence: ${unknown.map((p) => `${p.name}@${p.version}`).join(', ')}`);
      return 1;
    }
    console.log(`third-party-notices: ${pkgs.length} runtime packages, all declare a licence.`);
    return 0;
  }
  const text = renderNotices(pkgs);
  const outIdx = argv.indexOf('--out');
  if (outIdx !== -1) {
    const out = path.resolve(ROOT, argv[outIdx + 1]);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, text);
    console.log(`third-party-notices: wrote ${pkgs.length} packages to ${path.relative(ROOT, out)}`);
  } else {
    process.stdout.write(text);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main());
}
